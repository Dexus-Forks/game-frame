"""Each coding agent's copy of GameFrame's agents, generated from agents/re-*.md.

    from clients import CLIENTS, render, write
    files = render('gemini')          # {'.gemini/agents/re-tracer.md': text, ...}
    write(files, out_dir)

agents/re-*.md is the one source. Claude Code reads it through the .claude/agents link, and
VS Code and Cursor read .claude/agents too. The other clients get their own files:

    codex     .codex/agents/<name>.toml
    gemini    .gemini/agents/<name>.md
    copilot   .github/agents/<name>.agent.md
    opencode  .opencode/agents/<name>.md

The source's front matter uses Claude Code's tool names (`disallowedTools: [Agent, WebFetch]`).
TOOLS below maps each one to the other clients' names. Gemini CLI and Copilot only take an
allowlist, so their files list every tool except the denied ones. OpenCode takes a map of
denied permissions. Codex has no per-agent tool list; its file says the limits in words.
docs/working/agents.md has the same table.

It does not read or change the skills, and it writes only the files render() returns.
"""
import json
from pathlib import Path

from agents import agents
from paths import ROOT

# Claude Code's name -> (Gemini CLI names, Copilot alias, OpenCode permission, what Codex is told).
# A client's name is allowed unless every Claude tool that maps to it is denied.
TOOLS = {
    'Read':      (['read_file', 'read_many_files', 'list_directory'], 'read', 'read', 'read files'),
    'Grep':      (['grep_search'], 'search', 'grep', 'search file contents'),
    'Glob':      (['glob'], 'search', 'glob', 'list files by pattern'),
    'Edit':      (['replace'], 'edit', 'edit', 'edit files'),
    'Write':     (['write_file'], 'edit', 'edit', 'write files'),
    'Bash':      (['run_shell_command'], 'execute', 'bash', 'run shell commands'),
    'TodoWrite': (['write_todos'], 'todo', 'todowrite', 'keep a task list'),
    'Skill':     (['activate_skill'], None, 'skill', 'load skills'),
    'WebFetch':  (['web_fetch'], 'web', 'webfetch', 'fetch web pages'),
    'WebSearch': (['google_web_search'], 'web', 'websearch', 'search the web'),
    'Agent':     ([], 'agent', 'task', 'start other agents'),
    'mcp':       (['mcp_*'], None, None, 'use the MCP servers'),
}
CLIENTS = ('codex', 'gemini', 'copilot', 'opencode')
GENERATED = 'Generated by `gameframe agents --emit {client}` from agents/{name}.md. Edit that file, not this one.'


def mcp_servers():
    """The MCP servers in .mcp.json, which every agent may use. Copilot names them as `server/*`."""
    p = ROOT / '.mcp.json'
    return sorted(json.loads(p.read_text())['mcpServers']) if p.is_file() else []


def allowed(denied, column, every=False):
    """The names in one column of TOOLS that some allowed Claude tool still maps to, in order.

    With every=True, all the names in that column instead, allowed or not.
    """
    unknown = set(denied) - set(TOOLS)
    if unknown:
        raise ValueError(f'unknown tool names in disallowedTools: {sorted(unknown)} (known: {sorted(TOOLS)})')
    keep = []
    for claude, row in TOOLS.items():
        names = row[column] if isinstance(row[column], list) else [row[column]]
        for n in names:
            if n and (every or claude not in denied) and n not in keep:
                keep.append(n)
    return keep


def limits(denied):
    """One sentence that names what the agent may not do, for clients that cannot enforce it."""
    if not denied:
        return ''
    things = [TOOLS[t][3] for t in TOOLS if t in denied]
    said = ', '.join(things[:-1]) + (' or ' if len(things) > 1 else '') + things[-1]
    return f'You may not {said}. Your client does not enforce this, so keep to it yourself.'


def body(agent, with_limits=False):
    """The agent's body, with the lines every generated copy adds after its title.

    Every copy says to run git as `GAMEFRAME_AGENT=<name> git ...`: the gates
    (scripts/hooks/gate.py, the git pre-commit hook) read it to know which agent commits,
    since only Claude Code tells a hook the agent's name. with_limits adds limits().
    """
    lines = [f"Run every git command as `GAMEFRAME_AGENT={agent['name']} git ...`, so GameFrame's gates "
             'know which agent runs it.']
    if with_limits and agent['cannot_use']:
        lines.insert(0, limits(agent['cannot_use']))
    title, rest = agent['body'].split('\n', 1)
    return f"{title}\n\n" + '\n\n'.join(lines) + f"\n{rest}"


def render(client):
    from clients import codex, copilot, gemini, opencode
    module = {'codex': codex, 'gemini': gemini, 'copilot': copilot, 'opencode': opencode}[client]
    return {module.path(a['name']): module.render(a, GENERATED.format(client=client, name=a['name']))
            for a in agents()}


def write(files, out):
    for rel, text in files.items():
        p = Path(out) / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding='utf-8')
