#!/usr/bin/env python3
"""Write each wrapper DLL's export list and its stubs from its API table.

Usage: python3 wrappers/stubgen.py [--check] [CRATE ...]

  CRATE    a crate folder under wrappers/ with an api.tsv (glide, sgl, ati3dcif, s3dtkw,
           ddraw); default: every one that has an api.tsv
  --check  write nothing; exit 1 if a .def or src/stubs.rs differs from what would be written

Input: CRATE/api.tsv, the original library's API table (tools/pe/apitable.py, plus a `stub`
column), and the crate's Rust sources.
Output, for each crate:
  CRATE/NAME.def    every export of the original, with the internal name rustc gives it
                    (`_grDrawLine@8=grDrawLine@8` for stdcall, the bare name for cdecl). NAME
                    is the name of the .def file already there. scripts/zcc.sh links with it.
  CRATE/src/stubs.rs  one `shim::stub!` line for each export the crate does not implement.
                    A stub logs its call with its arguments and returns the `stub` value.

A call counts as implemented when a source file other than stubs.rs defines it with
`#[unsafe(no_mangle)]` and `extern "system"` (stdcall) or `extern "C"` (cdecl). A call
implemented with the other convention, or a `stub` of `-` with no implementation, is an
error. It prints how many calls each crate implements.

To implement a call, write it in the crate's own module, run this script and build. The
script removes the stub and keeps the export. It does not check argument types or what a call does, and it
does not touch crates without an api.tsv. Standard library only.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
IMPL = re.compile(r'#\[unsafe\(no_mangle\)\]\s*(?:#\[[^\]]*\]\s*)*pub\s+(?:unsafe\s+)?extern\s+"(system|C)"\s+fn\s+(\w+)')


def table(crate):
    rows = []
    with open(os.path.join(HERE, crate, 'api.tsv')) as f:
        lines = [l.rstrip('\n') for l in f if l.strip() and not l.startswith('#')]
    head = lines[0].split('\t')
    for l in lines[1:]:
        rows.append(dict(zip(head, l.split('\t'))))
    return rows


def implemented(crate):
    found = {}
    for root, _, files in os.walk(os.path.join(HERE, crate, 'src')):
        for name in files:
            if name.endswith('.rs') and name != 'stubs.rs':
                text = open(os.path.join(root, name)).read()
                for m in IMPL.finditer(text):
                    found[m.group(2)] = 'stdcall' if m.group(1) == 'system' else 'cdecl'
    return found


def value(v):
    if re.fullmatch(r'-\d+', v):
        return f'({v}i32) as u32'
    return v


def generate(crate):
    rows = table(crate)
    have = implemented(crate)
    errors = []
    defs, stubs = [], []
    for r in rows:
        sym, conv = r['symbol'], r['convention']
        if conv not in ('stdcall', 'cdecl'):
            errors.append(f'{r["export"]}: convention {conv}')
            continue
        defs.append(f'{r["export"]}={sym}@{r["bytes"]}' if conv == 'stdcall'
                    else (r['export'] if r['export'] == sym else f'{r["export"]}={sym}'))
        if sym in have:
            if have[sym] != conv:
                errors.append(f'{sym} is implemented as {have[sym]}, the original is {conv}')
            continue
        if r['stub'] == '-':
            errors.append(f'{sym} must be implemented (stub -)')
            continue
        n = int(r['bytes']) // 4 if conv == 'stdcall' else (int(r['params']) if r['params'].isdigit() else 0)
        args = ', '.join(f'a{i}' for i in range(n))
        abi = 'system' if conv == 'stdcall' else 'C'
        if r['returns'] == 'float':
            stubs.append(f'shim::stub!({abi} float {sym}({args}));')
        else:
            stubs.append(f'shim::stub!({abi} {sym}({args}) -> {value(r["stub"])});')
    def_path = [os.path.join(HERE, crate, f) for f in os.listdir(os.path.join(HERE, crate)) if f.endswith('.def')]
    if len(def_path) != 1:
        errors.append(f'{crate}: needs exactly one .def file')
        return errors, {}, 0, 0
    def_path = def_path[0]
    library = open(def_path).readline().strip()
    files = {
        def_path: library + '\nEXPORTS\n' + '\n'.join(defs) + '\n',
        os.path.join(HERE, crate, 'src', 'stubs.rs'): (
            f'//! Generated by wrappers/stubgen.py from api.tsv: do not edit. The {len(stubs)} calls of the\n'
            f'//! original library this one does not implement yet. Each logs its call (`shim::log`) and\n'
            '//! returns the value in api.tsv. To implement one, write it in its own module and run\n'
            '//! `python3 wrappers/stubgen.py` again.\n\n'
            '#![allow(non_snake_case)]\n\n' + '\n'.join(stubs) + ('\n' if stubs else '')),
    }
    return errors, files, len(rows) - len(stubs), len(rows)


def main(argv):
    if argv and argv[0] in ('-h', '--help'):
        print(__doc__)
        return 0
    check = '--check' in argv
    crates = [a for a in argv if not a.startswith('--')] or sorted(
        d for d in os.listdir(HERE) if os.path.isfile(os.path.join(HERE, d, 'api.tsv')))
    status = 0
    for crate in crates:
        errors, files, done, total = generate(crate)
        for e in errors:
            print(f'{crate}: {e}')
            status = 1
        stale = [p for p, text in files.items() if not os.path.exists(p) or open(p).read() != text]
        if check:
            for p in stale:
                print(f'{crate}: {os.path.relpath(p, HERE)} is out of date: run python3 wrappers/stubgen.py')
                status = 1
        else:
            for p in stale:
                open(p, 'w').write(files[p])
        print(f'{crate}: {done} of {total} calls implemented')
    return status


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
